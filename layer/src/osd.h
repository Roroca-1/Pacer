// Tiny CPU text rasterizer for the in-game OSD (5x7 bitmap font).
#pragma once
#include <stdint.h>
#include <string.h>
#include <string>
#include <vector>

namespace pacer {

static const uint8_t *glyph(char c) {
    static const uint8_t digits[10][7] = {
        {0x0E,0x11,0x13,0x15,0x19,0x11,0x0E},{0x04,0x0C,0x04,0x04,0x04,0x04,0x0E},
        {0x0E,0x11,0x01,0x02,0x04,0x08,0x1F},{0x1F,0x02,0x04,0x02,0x01,0x11,0x0E},
        {0x02,0x06,0x0A,0x12,0x1F,0x02,0x02},{0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E},
        {0x06,0x08,0x10,0x1E,0x11,0x11,0x0E},{0x1F,0x01,0x02,0x04,0x08,0x08,0x08},
        {0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E},{0x0E,0x11,0x11,0x0F,0x01,0x02,0x0C}};
    static const uint8_t letters[26][7] = {
        {0x0E,0x11,0x11,0x1F,0x11,0x11,0x11},{0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E},
        {0x0E,0x11,0x10,0x10,0x10,0x11,0x0E},{0x1C,0x12,0x11,0x11,0x11,0x12,0x1C},
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F},{0x1F,0x10,0x10,0x1E,0x10,0x10,0x10},
        {0x0E,0x11,0x10,0x17,0x11,0x11,0x0F},{0x11,0x11,0x11,0x1F,0x11,0x11,0x11},
        {0x0E,0x04,0x04,0x04,0x04,0x04,0x0E},{0x07,0x02,0x02,0x02,0x02,0x12,0x0C},
        {0x11,0x12,0x14,0x18,0x14,0x12,0x11},{0x10,0x10,0x10,0x10,0x10,0x10,0x1F},
        {0x11,0x1B,0x15,0x15,0x11,0x11,0x11},{0x11,0x11,0x19,0x15,0x13,0x11,0x11},
        {0x0E,0x11,0x11,0x11,0x11,0x11,0x0E},{0x1E,0x11,0x11,0x1E,0x10,0x10,0x10},
        {0x0E,0x11,0x11,0x11,0x15,0x12,0x0D},{0x1E,0x11,0x11,0x1E,0x14,0x12,0x11},
        {0x0F,0x10,0x10,0x0E,0x01,0x01,0x1E},{0x1F,0x04,0x04,0x04,0x04,0x04,0x04},
        {0x11,0x11,0x11,0x11,0x11,0x11,0x0E},{0x11,0x11,0x11,0x11,0x11,0x0A,0x04},
        {0x11,0x11,0x11,0x15,0x15,0x15,0x0A},{0x11,0x11,0x0A,0x04,0x0A,0x11,0x11},
        {0x11,0x11,0x11,0x0A,0x04,0x04,0x04},{0x1F,0x01,0x02,0x04,0x08,0x10,0x1F}};
    static const uint8_t dot[7] = {0,0,0,0,0,0x0C,0x0C}, colon[7] = {0,0x0C,0x0C,0,0x0C,0x0C,0},
                         slash[7] = {0,1,2,4,8,0x10,0}, dash[7] = {0,0,0,0x1F,0,0,0},
                         blank[7] = {0};
    if (c >= '0' && c <= '9') return digits[c - '0'];
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c >= 'A' && c <= 'Z') return letters[c - 'A'];
    if (c == '.') return dot;
    if (c == ':') return colon;
    if (c == '/') return slash;
    if (c == '-') return dash;
    return blank;
}

// RGBA8 (sRGB-encoded) canvas
struct Canvas {
    int w = 0, h = 0;
    std::vector<uint32_t> px; // 0xAABBGGRR
};

static const int OSD_COLS = 18, OSD_LINES = 2;

inline void osd_dims(uint32_t sw_h, int &scale, int &w, int &h) {
    scale = (int)(sw_h / 400);
    if (scale < 1) scale = 1;
    if (scale > 5) scale = 5;
    w = (OSD_COLS * 6 + 7) * scale;
    h = (OSD_LINES * 9 + 7) * scale;
}

inline void osd_render(Canvas &cv, int scale, const std::string lines[OSD_LINES],
                       const uint32_t colors[OSD_LINES]) {
    int w, h;
    osd_dims(scale * 400, scale, w, h);
    cv.w = w; cv.h = h;
    cv.px.assign((size_t)w * h, 0xE0141414u); // dark translucent-looking box (alpha ignored by present)
    // accent bar on the left
    for (int y = 0; y < h; y++)
        for (int x = 0; x < 2 * scale; x++) cv.px[(size_t)y * w + x] = 0xFF2BD47Cu;
    for (int l = 0; l < OSD_LINES; l++) {
        const std::string &s = lines[l];
        for (size_t i = 0; i < s.size() && (int)i < OSD_COLS; i++) {
            const uint8_t *g = glyph(s[i]);
            int ox = (5 + (int)i * 6) * scale, oy = (4 + l * 9) * scale;
            for (int gy = 0; gy < 7; gy++)
                for (int gx = 0; gx < 5; gx++)
                    if (g[gy] & (0x10 >> gx))
                        for (int sy = 0; sy < scale; sy++)
                            for (int sx = 0; sx < scale; sx++)
                                cv.px[(size_t)(oy + gy * scale + sy) * w + ox + gx * scale + sx] = colors[l];
        }
    }
}

} // namespace pacer
